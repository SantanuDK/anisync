// AniSync - Build browser/edition-specific packages
//
// The repo root is the FULL (developer) edition: load it unpacked in Chrome as-is.
// This script derives:
//
//   dist/chrome-store/  Chrome Web Store edition
//                       - official streaming services only (data/official-sites.json)
//                       - no remote site list; users enable extra sites themselves
//                       - "key" removed (the store assigns its own ID)
//   dist/firefox/       Full edition for Firefox desktop AND Android (developer use,
//                       installable unsigned in Firefox Nightly / Developer Edition)
//
// and zips each one when a zip-capable `tar` is available (built into Windows 10+).
//
// Usage: node scripts/build.js

const fs = require('fs');
const path = require('path');
const vm = require('vm');
const { execFileSync } = require('child_process');

// If your MAL app only accepts one redirect URL (the Chrome one), create a second
// MAL app with redirect https://anisync-api.YOUR-SUBDOMAIN.workers.dev/oauth/callback
// and put its client ID here. null = use the same MAL app as Chrome.
const FIREFOX_MAL_CLIENT_ID = null;

const ROOT = path.resolve(__dirname, '..');
const DIST = path.join(ROOT, 'dist');

const STORE_NAME = 'AniSync - Anime Tracker for MyAnimeList';
const MAL_HOSTS = ['https://api.myanimelist.net/*', 'https://myanimelist.net/*', 'https://api.aniskip.com/*'];

function copy(src, dest) {
  const stat = fs.statSync(src);
  if (stat.isDirectory()) {
    fs.mkdirSync(dest, { recursive: true });
    for (const entry of fs.readdirSync(src)) {
      copy(path.join(src, entry), path.join(dest, entry));
    }
  } else {
    fs.mkdirSync(path.dirname(dest), { recursive: true });
    fs.copyFileSync(src, dest);
  }
}

function zipDir(outDir, zipPath) {
  fs.rmSync(zipPath, { force: true });
  // Prefer Windows' bsdtar (supports zip); Git Bash's GNU tar does not.
  // (Avoid PowerShell Compress-Archive: on 5.1 it writes backslash paths that AMO rejects.)
  const winTar = process.env.SystemRoot && path.join(process.env.SystemRoot, 'System32', 'tar.exe');
  const tar = winTar && fs.existsSync(winTar) ? winTar : 'tar';
  try {
    const entries = fs.readdirSync(outDir); // manifest.json at the zip root, not in a subfolder
    execFileSync(tar, ['-a', '-c', '-f', zipPath, '-C', outDir, ...entries], { stdio: 'ignore' });
    return true;
  } catch (_) {
    return false;
  }
}

function buildTarget({ name, include, files = {}, transformManifest }) {
  const outDir = path.join(DIST, name);
  fs.rmSync(outDir, { recursive: true, force: true });
  fs.mkdirSync(outDir, { recursive: true });

  for (const item of include) {
    copy(path.join(ROOT, item), path.join(outDir, item));
  }
  for (const [rel, content] of Object.entries(files)) {
    fs.mkdirSync(path.dirname(path.join(outDir, rel)), { recursive: true });
    fs.writeFileSync(path.join(outDir, rel), content);
  }

  const manifest = JSON.parse(fs.readFileSync(path.join(ROOT, 'manifest.json'), 'utf8'));
  const result = transformManifest(manifest);
  fs.writeFileSync(path.join(outDir, 'manifest.json'), JSON.stringify(result, null, 2) + '\n');

  const zipPath = path.join(DIST, `anisync-${name}-${result.version}.zip`);
  const zipped = zipDir(outDir, zipPath);
  console.log(`  ${name}: ${path.relative(ROOT, outDir)}` +
    (zipped ? `  ->  ${path.relative(ROOT, zipPath)}` : '  (zip it manually; tar not available)'));
}

console.log('Building AniSync...');

// ---------- Chrome Web Store edition ----------
{
  const official = JSON.parse(fs.readFileSync(path.join(ROOT, 'data/official-sites.json'), 'utf8'));
  const officialDomains = [...new Set(official.sites.flatMap(s => s.domains))];
  // "*.example.com" also matches example.com itself
  const officialPatterns = officialDomains.map(d => `*://*.${d}/*`);

  const storeEdition = `// AniSync - Edition config (generated by scripts/build.js)
const ANISYNC_EDITION = {
  name: 'store',
  sitesUrl: null,
  bundledSitesPath: 'data/official-sites.json',
  staticContentScripts: false
};
`;

  buildTarget({
    name: 'chrome-store',
    include: ['background', 'content', 'popup', 'icons', 'data/official-sites.json'],
    files: { 'background/edition.js': storeEdition },
    transformManifest: (m) => {
      const out = { ...m };
      delete out.key;
      out.name = STORE_NAME;
      out.permissions = [...new Set([...(m.permissions || []), 'activeTab', 'scripting'])];
      out.host_permissions = [...MAL_HOSTS, ...officialPatterns];
      // Requested per site, only when the user clicks "Enable" in the popup
      out.optional_host_permissions = ['*://*/*'];
      out.content_scripts = [{
        matches: officialPatterns,
        js: ['content/detector.js'],
        run_at: 'document_idle',
        all_frames: true
      }];
      return out;
    }
  });
}

// ---------- Firefox (full edition, desktop + Android, developer use) ----------
{
  // Root edition config, with Firefox overrides: log in through a normal tab
  // (identity.launchWebAuthFlow does not exist on Firefox for Android).
  const sandbox = {};
  vm.runInNewContext(
    fs.readFileSync(path.join(ROOT, 'background/edition.js'), 'utf8') + '\nthis.result = ANISYNC_EDITION;',
    sandbox
  );
  const firefoxEdition = { ...sandbox.result, authFlow: 'tab' };
  if (FIREFOX_MAL_CLIENT_ID) firefoxEdition.malClientId = FIREFOX_MAL_CLIENT_ID;

  buildTarget({
    name: 'firefox',
    include: ['background', 'content', 'popup', 'icons', 'cloudflare-worker/sites.json'],
    files: {
      'background/edition.js':
        '// AniSync - Edition config (generated by scripts/build.js)\n' +
        `const ANISYNC_EDITION = ${JSON.stringify(firefoxEdition, null, 2)};\n`
    },
    transformManifest: (m) => {
      const out = { ...m };
      delete out.key;
      out.background = {
        scripts: ['background/edition.js', 'background/mal-client.js', 'background/service-worker.js']
      };
      out.browser_specific_settings = {
        gecko: {
          id: 'anisync@extension.local',
          strict_min_version: '115.0'
        },
        gecko_android: {
          strict_min_version: '120.0'
        }
      };
      return out;
    }
  });
}

// Remove the old single-edition Chrome build if present
fs.rmSync(path.join(DIST, 'chrome'), { recursive: true, force: true });
for (const f of fs.existsSync(DIST) ? fs.readdirSync(DIST) : []) {
  if (/^anisync-chrome-\d/.test(f)) fs.rmSync(path.join(DIST, f), { force: true });
}

console.log('Done.');
